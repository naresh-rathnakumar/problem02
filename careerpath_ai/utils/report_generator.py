"""
Comprehensive Career Guidance Report Generator.
Generates an executive-grade, multi-page PDF document covering:
1. Candidate Profile & Work Experience
2. Complete Skill Inventory with Evidence Classification
3. Multi-Role Compatibility Rankings & Transparent 4-Factor Scoring
4. Detailed Skill Gap Diagnosis & Priority Ratings
5. Personalized 12-Week Career Roadmap (Beginner, Intermediate, Advanced)
6. Interview Questions, Portfolio Milestones & Free Curated Resources
"""

import os
import re
from typing import Dict, Any, List
from fpdf import FPDF
from fpdf.enums import XPos, YPos


def sanitize_text(text: Any) -> str:
    """Sanitize and normalize text for safe, clean PDF rendering."""
    if text is None:
        return ""
    if not isinstance(text, str):
        text = str(text)

    # Convert common unicode symbols to clean printable characters
    replacements = {
        "\u2022": "*",    # Bullet •
        "\u2023": "*",    # Triangular bullet
        "\u25b6": ">",    # Arrow ▶
        "\u2013": "-",    # En-dash –
        "\u2014": "-",    # Em-dash —
        "\u2018": "'",    # Left single quote ‘
        "\u2019": "'",    # Right single quote ’
        "\u201c": '"',    # Left double quote “
        "\u201d": '"',    # Right double quote ”
        "\u2026": "...",  # Ellipsis …
        "\u00a0": " ",    # Non-breaking space
        "\t": "    ",     # Tab
    }
    for orig, rep in replacements.items():
        text = text.replace(orig, rep)

    # Strip unprintable control characters
    text = re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]", "", text)
    return text.strip()


class CareerReportPDF(FPDF):
    """Executive Report PDF with custom typography, auto-pagination, and coordinate control."""

    def __init__(self):
        super().__init__()
        self.set_auto_page_break(auto=True, margin=18)
        self.font_family_name = "Helvetica"
        self._setup_fonts()

    def _setup_fonts(self):
        """Register system TrueType font for clean rendering."""
        win_fonts = [
            (r"C:\Windows\Fonts\arial.ttf", r"C:\Windows\Fonts\arialbd.ttf"),
            (r"C:\Windows\Fonts\segoeui.ttf", r"C:\Windows\Fonts\segoeuib.ttf"),
            (r"C:\Windows\Fonts\calibri.ttf", r"C:\Windows\Fonts\calibrib.ttf"),
        ]
        for regular, bold in win_fonts:
            if os.path.exists(regular):
                try:
                    self.add_font("CustomUni", "", regular)
                    if os.path.exists(bold):
                        self.add_font("CustomUni", "B", bold)
                    else:
                        self.add_font("CustomUni", "B", regular)
                    self.font_family_name = "CustomUni"
                    return
                except Exception:
                    continue
        self.font_family_name = "Helvetica"

    @property
    def content_width(self) -> float:
        """Usable width between margins."""
        return self.w - self.l_margin - self.r_margin

    def header(self):
        self.set_font(self.font_family_name, "B", 13)
        self.set_text_color(27, 42, 74)
        self.set_x(self.l_margin)
        self.cell(self.content_width, 8, "CareerPath AI - Official Career Guidance & Skill Gap Report", border=0, align="C", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.set_draw_color(49, 130, 206)
        self.set_line_width(0.5)
        self.line(self.l_margin, self.get_y() + 1, self.w - self.r_margin, self.get_y() + 1)
        self.ln(4)

    def footer(self):
        self.set_y(-14)
        self.set_font(self.font_family_name, "", 8)
        self.set_text_color(140, 150, 165)
        self.set_x(self.l_margin)
        self.cell(self.content_width, 8, f"Page {self.page_no()} | Generated by CareerPath AI Multi-Agent System", border=0, align="C")

    def section_heading(self, title: str):
        """Render a major section header."""
        self.ln(4)
        self.set_x(self.l_margin)
        self.set_font(self.font_family_name, "B", 11)
        self.set_text_color(30, 64, 175)  # Professional navy/blue
        self.cell(self.content_width, 7, sanitize_text(title), border=0, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.set_draw_color(203, 213, 225)
        self.set_line_width(0.3)
        self.line(self.l_margin, self.get_y(), self.w - self.r_margin, self.get_y())
        self.ln(3)

    def sub_heading(self, title: str):
        """Render a subsection heading."""
        self.set_x(self.l_margin)
        self.set_font(self.font_family_name, "B", 10)
        self.set_text_color(27, 42, 74)
        self.cell(self.content_width, 6, sanitize_text(title), border=0, new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    def write_line(self, text: str, bold: bool = False, color=(40, 40, 40)):
        """Write a clean single line resetting coordinates to left margin."""
        self.set_x(self.l_margin)
        self.set_font(self.font_family_name, "B" if bold else "", 9)
        self.set_text_color(*color)
        clean = sanitize_text(text)
        try:
            self.cell(self.content_width, 5.5, clean, border=0, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        except Exception:
            ascii_text = clean.encode("ascii", errors="replace").decode("ascii")
            self.cell(self.content_width, 5.5, ascii_text, border=0, new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    def write_paragraph(self, text: str, bold: bool = False, color=(50, 50, 50)):
        """Write a multiline paragraph resetting coordinates properly."""
        if not text:
            return
        self.set_x(self.l_margin)
        self.set_font(self.font_family_name, "B" if bold else "", 9)
        self.set_text_color(*color)
        clean = sanitize_text(text)
        try:
            self.multi_cell(self.content_width, 5, clean, border=0, align="L", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        except Exception:
            ascii_text = clean.encode("ascii", errors="replace").decode("ascii")
            self.multi_cell(self.content_width, 5, ascii_text, border=0, align="L", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.ln(1)


def generate_career_report(
    resume_analysis: Dict[str, Any],
    match_results: List[Dict[str, Any]],
    skill_gaps: List[Dict[str, Any]],
    roadmap: Dict[str, Any],
    scoring_methodology: str = ""
) -> bytes:
    """Generate a complete, exhaustive, multi-page PDF career report."""
    pdf = CareerReportPDF()
    pdf.add_page()

    # =========================================================================
    # 1. CANDIDATE PROFILE SUMMARY
    # =========================================================================
    pdf.section_heading("1. Candidate Profile Summary")
    c_name = resume_analysis.get("candidate_name") or "Candidate"
    c_email = resume_analysis.get("email") or "Not specified"
    c_phone = resume_analysis.get("phone") or "Not specified"
    c_loc = resume_analysis.get("location") or "Not specified"
    c_exp = resume_analysis.get("total_experience_years", 0.0)

    pdf.write_line(f"Candidate Name: {c_name} | Email: {c_email}", bold=True)
    pdf.write_line(f"Location: {c_loc} | Total Professional Experience: {c_exp} Years")

    if resume_analysis.get("summary"):
        pdf.ln(1)
        pdf.write_paragraph(f"Professional Summary: {resume_analysis['summary']}")

    # Education
    edu_list = resume_analysis.get("education", [])
    if edu_list:
        pdf.ln(1)
        pdf.sub_heading("Educational Background:")
        for edu in edu_list:
            if isinstance(edu, dict):
                deg = edu.get("degree", "Degree")
                fld = f" in {edu['field']}" if edu.get("field") else ""
                inst = f" - {edu['institution']}" if edu.get("institution") else ""
                yr = f" ({edu['year']})" if edu.get("year") else ""
                pdf.write_line(f"  * {deg}{fld}{inst}{yr}")

    # Experience
    exp_list = resume_analysis.get("experience", [])
    if exp_list:
        pdf.ln(1)
        pdf.sub_heading("Experience History:")
        for exp in exp_list:
            if isinstance(exp, dict):
                t = exp.get("title", "Role")
                c = f" at {exp['company']}" if exp.get("company") else ""
                d = f" ({exp['duration']})" if exp.get("duration") else ""
                pdf.write_line(f"  * {t}{c}{d}", bold=True)
                if exp.get("description"):
                    pdf.write_paragraph(f"    {exp['description'][:200]}")

    # Projects
    proj_list = resume_analysis.get("projects", [])
    if proj_list:
        pdf.ln(1)
        pdf.sub_heading("Evidenced Projects:")
        for p in proj_list:
            if isinstance(p, dict):
                p_name = p.get("name", "Project")
                p_desc = p.get("description", "")
                p_tech = ", ".join(p.get("technologies", []))
                tech_str = f" [Tech: {p_tech}]" if p_tech else ""
                pdf.write_line(f"  * {p_name}{tech_str}", bold=True)
                if p_desc:
                    pdf.write_paragraph(f"    {p_desc}")

    # =========================================================================
    # 2. EXTRACTED SKILL INVENTORY & EVIDENCE CLASSIFICATION
    # =========================================================================
    pdf.section_heading("2. Extracted Skill Inventory & Evidence Classification")
    langs = ", ".join(resume_analysis.get("programming_languages", [])) or "None evidenced"
    fws = ", ".join(resume_analysis.get("frameworks_libraries", [])) or "None evidenced"
    tools = ", ".join(resume_analysis.get("tools_platforms", [])) or "None evidenced"
    dbs = ", ".join(resume_analysis.get("databases", [])) or "None evidenced"

    pdf.write_line(f"Programming Languages: {langs}", bold=True)
    pdf.write_line(f"Frameworks & Libraries: {fws}")
    pdf.write_line(f"Tools & Platforms / DevOps: {tools}")
    pdf.write_line(f"Databases & Data Storage: {dbs}")

    # Detailed Technical Evidence Classification
    tech_skills = resume_analysis.get("technical_skills", [])
    if tech_skills:
        pdf.ln(2)
        pdf.sub_heading("Verified Evidence Breakdown:")
        for ts in tech_skills:
            if isinstance(ts, dict):
                name = ts.get("name", "")
                ev = ts.get("evidence", "Mentioned")
                ctx = f" ({ts['context']})" if ts.get("context") else ""
                tag = "[Strongly Demonstrated]" if "Strong" in ev else "[Mentioned in Resume]"
                pdf.write_line(f"  * {name} -- {tag}{ctx}")

    # Soft Skills
    soft = resume_analysis.get("soft_skills", [])
    if soft:
        soft_names = [s.get("name", str(s)) if isinstance(s, dict) else str(s) for s in soft]
        pdf.ln(1)
        pdf.write_line(f"Evidenced Soft Skills: {', '.join(soft_names)}")

    # =========================================================================
    # 3. JOB ROLE COMPATIBILITY & MATHEMATICAL SCORING
    # =========================================================================
    pdf.add_page()
    pdf.section_heading("3. Job Role Compatibility & Transparent Scoring")
    pdf.write_paragraph(
        "Match scores are calculated deterministically: Required Technical Skills (50%), "
        "Preferred Technical Skills (20%), Project Evidence (20%), and Education/Experience Alignment (10%)."
    )

    for idx, m in enumerate(match_results):
        r_title = m.get("job_title", f"Role #{idx+1}")
        score = float(m.get("overall_score") or 0.0)
        req = float(m.get("required_skills_score") or 0.0)
        pref = float(m.get("preferred_skills_score") or 0.0)
        proj = float(m.get("project_evidence_score") or 0.0)
        edu = float(m.get("education_experience_score") or 0.0)

        pdf.ln(2)
        pdf.sub_heading(f"Role #{idx+1}: {r_title}  --  Overall Compatibility: {score:.1f}%")
        pdf.write_line(f"  Scoring Breakdown: Required: {req:.0f}% | Preferred: {pref:.0f}% | Projects: {proj:.0f}% | Education/Exp: {edu:.0f}%")

        if m.get("suitability"):
            pdf.write_paragraph(f"  Suitability Assessment: {m['suitability']}")

        # Matched Skills
        matched = [s for s in m.get("matched_skills", []) if isinstance(s, dict) and s.get("matched")]
        if matched:
            matched_str = ", ".join([f"{s['skill']} ({s.get('evidence', 'Evidenced')})" for s in matched[:8]])
            pdf.write_paragraph(f"  Matched Skills: {matched_str}")

        # Missing Skills
        missing = m.get("missing_skills", [])
        if missing:
            pdf.write_line(f"  Missing Skills (Not Evidenced in Resume): {', '.join(missing)}", bold=True, color=(185, 28, 28))

    # =========================================================================
    # 4. SKILL GAP DIAGNOSIS & PRIORITY RATINGS
    # =========================================================================
    pdf.add_page()
    pdf.section_heading("4. Skill Gap Diagnosis & Priority Ratings")
    pdf.write_paragraph(
        "Skills absent from the candidate profile are strictly labeled as 'Not evidenced in resume'. "
        "Priorities represent: High (Core Mandate), Medium (Key Competency), Low (Bonus Qualification)."
    )

    for g in skill_gaps:
        g_title = g.get("job_title", "Target Role")
        cov = float(g.get("coverage_percentage") or 0.0)
        pdf.ln(2)
        pdf.sub_heading(f"Role: {g_title}  (Skill Coverage: {cov:.1f}%)")

        critical = g.get("critical_gaps", [])
        if critical:
            pdf.write_line(f"  Critical Missing Gaps: {', '.join(critical)}", bold=True, color=(185, 28, 28))

        # Not Evidenced Skills
        not_ev = g.get("not_evidenced", [])
        if not_ev:
            pdf.write_line("  Identified Skill Gaps:")
            for item in not_ev:
                if isinstance(item, dict):
                    sk = item.get("skill", "")
                    prio = item.get("priority", "Medium")
                    rec = item.get("recommendation", "")
                    reason = item.get("importance_reason", "")
                    projs = item.get("improvable_projects", [])
                    proj_str = f" [Upgrade Project: {', '.join(projs)}]" if projs else ""
                    pdf.write_line(f"    * [{prio} Priority] {sk}: {reason}")
                    if rec:
                        pdf.write_paragraph(f"      Recommendation: {rec}{proj_str}")

    # =========================================================================
    # 5. PERSONALIZED 12-WEEK CAREER ROADMAP
    # =========================================================================
    pdf.add_page()
    pdf.section_heading("5. Personalized 12-Week Career Roadmap")
    r_target = roadmap.get("job_title") or "Target Role"
    r_dur = roadmap.get("total_duration") or "12-16 Weeks"
    pdf.write_line(f"Target Career Role: {r_target} | Estimated Duration: {r_dur}", bold=True)

    if roadmap.get("overview"):
        pdf.write_paragraph(f"Curriculum Strategic Overview: {roadmap['overview']}")

    # 3 Progressive Phases
    phases = [
        ("beginner", "PHASE 1: BEGINNER (Foundations & Core Missing Gaps)", (30, 64, 175)),
        ("intermediate", "PHASE 2: INTERMEDIATE (Integration & Scalability)", (202, 138, 4)),
        ("advanced", "PHASE 3: ADVANCED (Production Readiness & Capstone)", (185, 28, 28)),
    ]

    for key, phase_title, color in phases:
        lvl = roadmap.get(key, {})
        if isinstance(lvl, dict) and lvl:
            pdf.ln(3)
            pdf.sub_heading(f"{phase_title} -- {lvl.get('duration', '')}")
            if lvl.get("description"):
                pdf.write_paragraph(f"Goal: {lvl['description']}")

            milestones = lvl.get("milestones", [])
            for ms in milestones:
                if isinstance(ms, dict):
                    wk = ms.get("week", "Milestone")
                    obj = ms.get("objective", "Learning Objective")
                    pdf.write_line(f"  * {wk}: {obj}", bold=True)

                    if ms.get("topics"):
                        pdf.write_paragraph(f"    Topics to Learn: {', '.join(ms['topics'])}")
                    if ms.get("practical_tasks"):
                        for task in ms["practical_tasks"]:
                            pdf.write_line(f"      - Task: {task}")
                    if ms.get("resources"):
                        pdf.write_paragraph(f"      Free Resources: {', '.join(ms['resources'])}")

            projs = lvl.get("projects", [])
            if projs:
                pdf.write_line(f"  Milestone Projects: {', '.join(projs)}", bold=True)
            tools = lvl.get("tools", [])
            if tools:
                pdf.write_line(f"  Tools & Platforms to Master: {', '.join(tools)}")

    # =========================================================================
    # 6. INTERVIEW PREP & PORTFOLIO ENHANCEMENT
    # =========================================================================
    pdf.add_page()
    pdf.section_heading("6. Interview Preparation & Portfolio Enhancement")

    # Interview Topics
    interview_topics = roadmap.get("interview_topics", [])
    if interview_topics:
        pdf.sub_heading(f"Role-Specific Technical & Architectural Interview Questions ({r_target}):")
        for q in interview_topics:
            pdf.write_line(f"  * {q}")
        pdf.ln(2)

    # Portfolio Suggestions
    portfolio_suggs = roadmap.get("portfolio_suggestions", [])
    if portfolio_suggs:
        pdf.sub_heading("Portfolio Milestone & Enhancement Suggestions:")
        for s in portfolio_suggs:
            pdf.write_line(f"  * {s}")
        pdf.ln(2)

    # Free Curated Learning Resources
    free_res = roadmap.get("free_resources", [])
    if free_res:
        pdf.sub_heading("Recommended Free Educational Resources:")
        for r in free_res:
            pdf.write_line(f"  * {r}")

    # Telemetry Note
    pdf.ln(4)
    pdf.write_line(
        "Report verified and compiled by CareerPath AI Multi-Agent System (Agents 1-4).",
        bold=True,
        color=(100, 116, 139)
    )

    # Compile valid binary output
    output = pdf.output()
    if isinstance(output, (bytes, bytearray)):
        return bytes(output)
    if isinstance(output, str):
        return output.encode("latin-1", errors="replace")
    return bytes(output)
